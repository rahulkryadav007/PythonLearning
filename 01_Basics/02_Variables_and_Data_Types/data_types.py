# ============================================================
# DATA TYPES — BASIC TO INTERMEDIATE
# ============================================================

# int: whole/without-decimal number
age = 24

# float: decimal number
height = 5.5

# str: text data
name = "Rahul"

# bool: True ya False value
is_student = True

# None: abhi koi actual value nahi hai
result = None

# Collections bhi Python ke important built-in types hain
skills = ["Java", "Python", "SQL"]          # list
coordinates = (10, 20)                        # tuple
unique_numbers = {10, 20, 30}                # set
student = {"name": "Rahul", "age": 24}     # dictionary

# Har variable ka type check kar rahe hain
print(type(age))
print(type(height))
print(type(name))
print(type(is_student))
print(type(result))
print(type(skills))
print(type(coordinates))
print(type(unique_numbers))
print(type(student))
