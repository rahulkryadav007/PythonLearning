# ============================================================
# VARIABLES — BASIC TO INTERMEDIATE
# ============================================================

# Student ka naam variable mein store kar rahe hain
name = "Rahul"

# Student ki age integer value hai
age = 24

# Marks decimal value mein hain
marks = 85.5

# Boolean batata hai ki condition True hai ya False
is_passed = True

print("Name:", name)
print("Age:", age)
print("Marks:", marks)
print("Passed:", is_passed)

# ------------------------------------------------------------
# type() se hum value ka data type check kar sakte hain.
# ------------------------------------------------------------
print(type(name))
print(type(age))
print(type(marks))
print(type(is_passed))

# ------------------------------------------------------------
# Variables ko calculate karne ke liye reuse kar sakte hain.
# ------------------------------------------------------------
price = 500
quantity = 3

total = price * quantity

print("Total Price:", total)
